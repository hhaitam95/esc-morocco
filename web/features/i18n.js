const LANGUAGE_STORAGE_KEY =
  "esc_language";

const LANGUAGE_META = Object.freeze({
  en: {
    flag: "🇬🇧",
    short: "EN",
  },
  fr: {
    flag: "🇫🇷",
    short: "FR",
  },
  ar: {
    flag: "🇸🇦",
    short: "AR",
  },
});

let currentLanguage = "en";
let changeHandler = () => {};

function readLanguage() {
  try {
    return (
      localStorage.getItem(
        LANGUAGE_STORAGE_KEY,
      ) || "en"
    );
  } catch {
    return "en";
  }
}

export function locale() {
  if (currentLanguage === "fr") {
    return "fr-FR";
  }

  if (currentLanguage === "ar") {
    return "ar-MA";
  }

  return "en-GB";
}

export function t(key) {
  return (
    translations[currentLanguage]?.[key] ??
    translations.en?.[key] ??
    key
  );
}

function updateLanguageControl() {
  const meta =
    LANGUAGE_META[
      currentLanguage
    ] || LANGUAGE_META.en;

  const flag =
    document.getElementById(
      "language-dropdown-flag",
    );

  const label =
    document.getElementById(
      "language-dropdown-label",
    );

  if (flag) {
    flag.textContent =
      meta.flag;
  }

  if (label) {
    label.textContent =
      meta.short;
  }
}

function applyTranslations() {
  document.documentElement.lang =
    currentLanguage;

  document.documentElement.dir =
    currentLanguage === "ar"
      ? "rtl"
      : "ltr";

  document
    .querySelectorAll(
      "[data-i18n]",
    )
    .forEach(
      (element) => {
        element.textContent =
          t(
            element.dataset.i18n,
          );
      },
    );

  document
    .querySelectorAll(
      "[data-i18n-placeholder]",
    )
    .forEach(
      (element) => {
        element.placeholder =
          t(
            element.dataset
              .i18nPlaceholder,
          );
      },
    );

  updateLanguageControl();
  changeHandler();
}

export function initLanguage(
  onChange = () => {},
) {
  changeHandler =
    onChange;

  const stored =
    readLanguage();

  if (
    translations[stored]
  ) {
    currentLanguage =
      stored;
  }

  const toggle =
    document.getElementById(
      "language-dropdown-toggle",
    );

  const menu =
    document.getElementById(
      "language-dropdown-menu",
    );

  if (toggle && menu) {
    toggle.addEventListener(
      "click",
      (event) => {
        event.stopPropagation();

        menu.hidden =
          !menu.hidden;
      },
    );

    document.addEventListener(
      "click",
      (event) => {
        if (
          !event.target.closest(
            ".language-dropdown",
          )
        ) {
          menu.hidden = true;
        }
      },
    );
  }

  document
    .querySelectorAll(
      ".language-option",
    )
    .forEach(
      (button) => {
        button.addEventListener(
          "click",
          () => {
            const next =
              button.dataset.language;

            if (
              !translations[next]
            ) {
              return;
            }

            currentLanguage =
              next;

            try {
              localStorage.setItem(
                LANGUAGE_STORAGE_KEY,
                currentLanguage,
              );
            } catch {
              // Optional persistence.
            }

            if (menu) {
              menu.hidden = true;
            }

            applyTranslations();
          },
        );
      },
    );

  applyTranslations();
}

export function currentLanguage() {
  return currentLanguage;
}
